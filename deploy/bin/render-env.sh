#!/usr/bin/env bash
# Render one environment's .env from its name. This is the heart of "one
# template, N value-sets": every per-env value is DERIVED from the env name;
# only secrets come from the surrounding environment (GitHub Actions secrets in
# CI, your shell locally). Prints the path of the file it wrote.
#
#   deploy/bin/render-env.sh <env-name>     # "prod" | "staging" | "pr-<n>"
#
# Each env runs its OWN Postgres (deploy/stack), so DB hosts are the in-stack
# service names (postgres / powersync-storage) and the DB names are fixed —
# isolation comes from the separate container + volume, not a namespaced name.
set -euo pipefail

ENV_NAME="${1:?usage: render-env.sh <env-name>}"

# A token safe for DNS aliases: pr-101 -> pr-101 (lowercased, non-alnum → -).
SLUG="$(printf '%s' "$ENV_NAME" | tr 'A-Z' 'a-z' | tr -c 'a-z0-9' '-')"
SLUG="${SLUG%-}"
STACK="pace-${SLUG}"

BASE_DOMAIN="${BASE_DOMAIN:-paceproductivity.app}"
# prod serves the apex; every other env is a subdomain of it.
if [ "$ENV_NAME" = "prod" ]; then
  HOST="${BASE_DOMAIN}"
else
  HOST="${ENV_NAME}.${BASE_DOMAIN}"
fi

POSTGRES_USER="${POSTGRES_USER:-pace}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-pace}"

# Shared across throwaway envs is fine. Supply via env in CI; the dev default
# keeps local `docker compose config` / previews working out of the box.
BETTER_AUTH_SECRET="${BETTER_AUTH_SECRET:-dev-insecure-secret-change-me}"

IMAGE_WEB="${IMAGE_WEB:-ghcr.io/nickzou/pace/web:latest}"
IMAGE_API="${IMAGE_API:-ghcr.io/nickzou/pace/api:latest}"
IMAGE_API_MIGRATE="${IMAGE_API_MIGRATE:-ghcr.io/nickzou/pace/api-migrate:latest}"
IMAGE_API_SEED="${IMAGE_API_SEED:-ghcr.io/nickzou/pace/api-seed:latest}"
POWERSYNC_IMAGE="${POWERSYNC_IMAGE:-journeyapps/powersync-service:1.23.3}"
POSTGRES_IMAGE="${POSTGRES_IMAGE:-postgres:17-alpine}"

# In-stack service names on the env's private network (fixed DB names).
DB_URL="postgresql://${POSTGRES_USER}:${POSTGRES_PASSWORD}@postgres:5432/pace"
STORAGE_URL="postgresql://${POSTGRES_USER}:${POSTGRES_PASSWORD}@powersync-storage:5432/powersync"

# Email verification. Prod is the ONLY env that gates + actually sends: the flag is
# on and SMTP points at Resend (the key comes from the environment — the
# PROD_RESEND_API_KEY secret in CI). Every other env keeps the gate OFF, so sign-up
# sends no mail and needs no SMTP server (matches CI). WEB_URL is the public origin
# every verification link points at, so one link works from web/desktop/mobile.
if [ "$ENV_NAME" = "prod" ]; then
  REQUIRE_EMAIL_VERIFICATION=true
  SMTP_HOST=smtp.resend.com
  SMTP_PORT=587
  SMTP_USER=resend
  SMTP_PASS="${RESEND_API_KEY:?RESEND_API_KEY is required for prod (set the PROD_RESEND_API_KEY secret)}"
else
  REQUIRE_EMAIL_VERIFICATION=false
  SMTP_HOST=""
  SMTP_PORT=""
  SMTP_USER=""
  SMTP_PASS=""
fi
EMAIL_FROM="Pace <no-reply@${BASE_DOMAIN}>"

OUT_DIR="$(cd "$(dirname "$0")/.." && pwd)/envs"
mkdir -p "$OUT_DIR"
OUT="${OUT_DIR}/${ENV_NAME}.env"

cat > "$OUT" <<EOF
# Generated by deploy/bin/render-env.sh for env "${ENV_NAME}".
# Do not edit by hand and do not commit (holds secrets). Regenerate to change.
ENV_NAME=${ENV_NAME}
STACK=${STACK}
HOST=${HOST}
COMPOSE_PROJECT_NAME=${STACK}

IMAGE_WEB=${IMAGE_WEB}
IMAGE_API=${IMAGE_API}
IMAGE_API_MIGRATE=${IMAGE_API_MIGRATE}
IMAGE_API_SEED=${IMAGE_API_SEED}
POWERSYNC_IMAGE=${POWERSYNC_IMAGE}
POSTGRES_IMAGE=${POSTGRES_IMAGE}

POSTGRES_USER=${POSTGRES_USER}
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
DATABASE_URL=${DB_URL}

BETTER_AUTH_SECRET=${BETTER_AUTH_SECRET}
BETTER_AUTH_URL=https://${HOST}
TRUSTED_ORIGINS=https://${HOST},tauri://localhost,http://tauri.localhost

API_URL=https://${HOST}
POWERSYNC_URL=https://${HOST}/powersync

REQUIRE_EMAIL_VERIFICATION=${REQUIRE_EMAIL_VERIFICATION}
WEB_URL=https://${HOST}
EMAIL_FROM="${EMAIL_FROM}"
SMTP_HOST=${SMTP_HOST}
SMTP_PORT=${SMTP_PORT}
SMTP_USER=${SMTP_USER}
SMTP_PASS="${SMTP_PASS}"

PS_DATA_SOURCE_URI=${DB_URL}
PS_STORAGE_SOURCE_URI=${STORAGE_URL}
PS_JWKS_URL=http://${STACK}-api:3001/api/auth/jwks
PS_PORT=8080
EOF

echo "$OUT"
